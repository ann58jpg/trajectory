import type { Explanation, Profession, Rec, University } from "@/lib/schemas";

/** Шаблонные тексты демо-режима: собираются из фактов движка, без ИИ. */
export function professionTemplate(prof: Profession, rec?: Rec | null): Explanation {
  const why = rec?.reasons.length
    ? `Почему тебе: ${rec.reasons.slice(0, 3).join("; ")}.`
    : `«${prof.name}» — это ${prof.tasks.slice(0, 2).map((t) => t.toLowerCase()).join(" и ")}. Подходит тем, кому близко: ${prof.skills.slice(0, 3).join(", ").toLowerCase()}.`;
  return {
    whyYou: why,
    dayInLife: prof.dayInLife,
    askStudents: [
      `С какого курса реально начинают работать по профессии «${prof.name}» и где?`,
      "Какие предметы на старших курсах самые полезные, а какие — для галочки?",
      "Куда устроились выпускники прошлого года и сколько им предложили на старте?",
      `Какие навыки (${prof.stack.slice(0, 3).join(", ")}) дают в вузе, а что приходится учить самому?`,
    ],
  };
}

export function universityTemplate(uni: University, programNames: string[]): Explanation {
  return {
    whyYou: `${uni.short} — ${uni.description}${programNames.length ? ` Тебе могут подойти программы: ${programNames.slice(0, 3).join(", ")}.` : ""}`,
    dayInLife:
      `Приезжай на день открытых дверей или просто погуляй по кампусу в учебный день. Загляни в столовую и библиотеку, посмотри доски объявлений — ` +
      `какие клубы, хакатоны и стажировки там висят. Зайди на кафедру своей программы и спроси, можно ли посидеть на паре. ` +
      `Почитай сообщества студентов в VK и Telegram — там видно, чем живут люди на самом деле.`,
    askStudents: [
      "Сколько реально длится учебный день и остаётся ли время на подработку?",
      "Что в программе оказалось не так, как обещали на дне открытых дверей?",
      "Как устроены практика и стажировки: компании сами приходят или ищешь сам?",
      uni.dorm ? "Как с общежитием: сколько человек в комнате, легко ли получить место первокурснику?" : "Где живут иногородние студенты и сколько стоит жильё рядом?",
      ...(uni.vuc ? ["Как попасть в военный учебный центр и сколько времени он занимает?"] : []),
    ],
  };
}
