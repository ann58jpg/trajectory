/**
 * Слова, которых не должно быть в текстах интерфейса (их проверяет tests/unit/copy.test.ts).
 * Список хранится здесь, а не в copy.ts, чтобы промпт ИИ мог сослаться на него, не нарушая проверку.
 */
const Ц = "[а-яё]"; // буква кириллицы — граница слова для регулярных выражений

export const BANNED: { word: string; re: RegExp }[] = [
  { word: "движок", re: new RegExp(`(?<!${Ц})движ(ок|ка|ку|ком|ке)(?!${Ц})`, "i") },
  { word: "скоринг", re: new RegExp(`(?<!${Ц})скоринг`, "i") },
  { word: "метч", re: new RegExp(`(?<!${Ц})метч`, "i") },
  { word: "траектория", re: new RegExp(`(?<!${Ц})траектори`, "i") },
  { word: "вес", re: new RegExp(`(?<!${Ц})вес(а|у|ом|е|ы|ов|ам|ами|ах)?(?!${Ц})`, "i") },
  { word: "фактор", re: new RegExp(`(?<!${Ц})фактор`, "i") },
  { word: "профиль компетенций", re: /профил\S* компетенц/i },
  { word: "уникальный", re: new RegExp(`(?<!${Ц})уникальн`, "i") },
  { word: "инновационный", re: new RegExp(`(?<!${Ц})инновацион`, "i") },
  { word: "путь к успеху", re: /пут\S* к успеху/i },
  { word: "раскрой потенциал", re: /раскр\S* (свой |твой )?потенциал/i },
  { word: "ВУЦ", re: /(?<![А-ЯЁA-Z])ВУЦ(?![А-ЯЁA-Z])/ },
  { word: "ДВИ", re: /(?<![А-ЯЁA-Z])ДВИ(?![А-ЯЁA-Z])/ },
  { word: "СПО", re: /(?<![А-ЯЁA-Z])СПО(?![А-ЯЁA-Z])/ },
  { word: "!!", re: /!!/ },
];

/** Для промпта ИИ: «не используй слова …». */
export const BANNED_FOR_PROMPT = BANNED.filter((b) => /^[а-яё ]+$/i.test(b.word)).map((b) => `«${b.word}»`).join(", ");
